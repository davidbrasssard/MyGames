// Fetches the Triple Tile pictures from Microsoft's Fluent Emoji (MIT), "3D" style, resizes them to 128x128 PNG
// with sharp (devDependency) and writes:
//   public/triple-tiles/<id>.png          the pictures (served as plain files, cached for offline by the service worker)
//   src/pictures/tripleTilesFluent.ts     the "triple-tiles-fluent" collection definition
// The picture list lives in scripts/triple-tiles.json (id, Fluent folder name, FR and EN names).
// Run with:  node scripts/fetch-triple-tiles.mjs
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { readFileSync } from 'node:fs';
import sharp from 'sharp';

// Same pinned commit as scripts/fetch-tiles.mjs so the result is reproducible.
const FLUENT_REF = '1ffb34c752ecf5d402f04cfb4b392c77f57c54bc';
const SIZE = 128;
const tiles = JSON.parse(readFileSync(new URL('./triple-tiles.json', import.meta.url), 'utf8'));

mkdirSync(new URL('../public/triple-tiles/', import.meta.url), { recursive: true });
copyFileSync(new URL('../public/tiles/LICENSE.txt', import.meta.url), new URL('../public/triple-tiles/LICENSE.txt', import.meta.url));

let total = 0;
for (const tile of tiles) {
  const file = `${tile.source.toLowerCase().replace(/ /g, '_')}_3d.png`;
  const url = `https://raw.githubusercontent.com/microsoft/fluentui-emoji/${FLUENT_REF}/assets/${encodeURIComponent(tile.source)}/3D/${file}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${tile.id}: HTTP ${response.status} for ${url}`);
  const png = await sharp(Buffer.from(await response.arrayBuffer()))
    .resize(SIZE, SIZE, { fit: 'contain', background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png({ compressionLevel: 9, effort: 10, palette: true, quality: 90 })
    .toBuffer();
  writeFileSync(new URL(`../public/triple-tiles/${tile.id}.png`, import.meta.url), png);
  total += png.length;
  console.log(`${tile.id.padEnd(14)} ${String(png.length).padStart(6)} bytes`);
}
console.log(`total ${total} bytes for ${tiles.length} pictures`);

const entries = tiles
  .map((t) => `  { id: '${t.id}', name: { fr: '${t.fr}', en: '${t.en}' } },`)
  .join('\n');
writeFileSync(
  new URL('../src/pictures/tripleTilesFluent.ts', import.meta.url),
  `// GENERATED by scripts/fetch-triple-tiles.mjs from scripts/triple-tiles.json. Do not edit by hand.
// Pictures: Microsoft Fluent Emoji, "3D" style, 128x128 PNG, MIT license (see THIRD_PARTY_NOTICES.md).
import type { PictureCollection } from './types';

export const TRIPLE_TILES_FLUENT: PictureCollection = {
  id: 'triple-tiles-fluent',
  basePath: 'triple-tiles',
  pictures: [
${entries}
  ],
};
`,
);
